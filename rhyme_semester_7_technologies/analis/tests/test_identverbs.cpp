#include <gtest/gtest.h>
#include "IdentVerbs.h"

using namespace iverbs;

namespace {

struct ReportData {
    int tp = 0, fp = 0, fn = 0;
    std::vector<std::tuple<std::string, int, int>> detected; // word, score, sentence#
    std::vector<std::pair<std::string, int>> false_pos;      // word, sentence#
    std::vector<std::pair<std::string, int>> false_neg;      // word, sentence#
};

void run_and_report(const std::string& title,
                    const std::vector<std::pair<std::string, std::set<std::string>>>& cases,
                    uint8_t threshold) {
    ReportData rd;

    for (size_t i = 0; i < cases.size(); ++i) {
        const auto& sentence = cases[i].first;
        const auto& expected = cases[i].second;

        IdentVerbs iv(sentence);
        auto found = iv.ident_verbs(threshold);

        std::set<std::string> found_set;
        for (const auto& f : found) {
            found_set.insert(f.verb);
            rd.detected.emplace_back(f.verb, int(f.score), int(i + 1));
        }
        for (const auto& f : found_set) {
            if (expected.count(f)) {
                ++rd.tp;
            } else {
                ++rd.fp;
                rd.false_pos.emplace_back(f, int(i + 1));
            }
        }
        for (const auto& e : expected) {
            if (!found_set.count(e)) {
                ++rd.fn;
                rd.false_neg.emplace_back(e, int(i + 1));
            }
        }
    }

    const double precision = (rd.tp + rd.fp) ? double(rd.tp) / (rd.tp + rd.fp) : 0.0;
    const double recall    = (rd.tp + rd.fn) ? double(rd.tp) / (rd.tp + rd.fn) : 0.0;

    std::cout << "\n===== " << title << " =====\n";
    std::cout << "Порог: " << int(threshold) << "   Предложений: " << cases.size() << "\n\n";

    std::cout << "--- Обнаруженные слова (score >= порога) ---\n";
    std::cout << std::left << std::setw(22) << "Слово"
              << std::setw(8) << "Score" << "Предл#\n";
    std::cout << std::string(38, '-') << "\n";
    for (const auto& [w, s, n] : rd.detected) {
        std::cout << std::left << std::setw(22) << w
                  << std::setw(8) << s << n << "\n";
    }

    if (!rd.false_pos.empty()) {
        std::cout << "\n--- Ложные срабатывания (FP) ---\n";
        for (const auto& [w, n] : rd.false_pos)
            std::cout << "  " << w << "  (предл. " << n << ")\n";
    }
    if (!rd.false_neg.empty()) {
        std::cout << "\n--- Пропущенные глаголы (FN) ---\n";
        for (const auto& [w, n] : rd.false_neg)
            std::cout << "  " << w << "  (предл. " << n << ")\n";
    }

    std::cout << "\n=====================================\n";
    std::cout << "TP (нашёл глагол)     = " << rd.tp << "\n";
    std::cout << "FP (нашёл не глагол)  = " << rd.fp << "\n";
    std::cout << "FN (пропустил глагол) = " << rd.fn << "\n";
    std::cout << "Точность (precision)  = " << std::fixed << std::setprecision(3) << precision << "\n";
    std::cout << "Полнота (recall)      = " << std::fixed << std::setprecision(3) << recall << "\n";
    std::cout << "Порог                 = " << int(threshold) << "\n";
    std::cout << "=====================================\n";
}

} // namespace

// проверка корректности парсинга

TEST(Parse, SimpleSentence) {
    IdentVerbs iv("Жил да был черный кот за углом.");
    ASSERT_EQ(iv.words().size(), 7u);
    EXPECT_EQ(iv.words()[0], "жил");
    EXPECT_EQ(iv.words()[6], "углом");
}

TEST(Parse, PunctuationAttached) {
    IdentVerbs iv("И кота ненавидел: весь дом (кто-то)!");
    ASSERT_EQ(iv.words().size(), 6u);
    EXPECT_EQ(iv.words()[5], "кто-то");
}

TEST(Parse, ApostropheInsideWord) {
    IdentVerbs iv("Д'Артаньян и кто-то ещё");
    ASSERT_EQ(iv.words().size(), 4u);
    EXPECT_EQ(iv.words()[0], "д'артаньян");
    EXPECT_EQ(iv.words()[1], "и");
    EXPECT_EQ(iv.words()[2], "кто-то");
    EXPECT_EQ(iv.words()[3], "ещё");
}

