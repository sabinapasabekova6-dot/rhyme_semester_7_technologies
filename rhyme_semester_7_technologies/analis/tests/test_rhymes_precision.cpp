TEST(RhymesMegaTest, AccuracyReport) {
    auto pairs = build_pairs();
    const size_t total = pairs.size();
    size_t n_pos = 0, n_neg = 0;
    for (auto& p : pairs) (p.expected ? n_pos : n_neg)++;

    cout << "\n==============================================================\n"
         << "     ТЕСТ ТОЧНОСТИ ОПРЕДЕЛЕНИЯ ГЛАГОЛЬНЫХ РИФМ\n"
         << "==============================================================\n"
         << "Всего пар:       " << total << "\n"
         << "  из них рифм:   " << n_pos << "\n"
         << "  не-рифм:       " << n_neg << "\n\n";

    // ---------- сетка порогов ----------
    cout << "--------------------------------------------------------------\n"
         << "  Точность по порогам similarity (T)\n"
         << "--------------------------------------------------------------\n"
         << "  T     TP   FP   TN   FN    Prec       Rec        Acc\n"
         << "--------------------------------------------------------------\n";

    double best_acc = 0.0, best_t = 0.0;
    for (double t : {0.3, 0.4, 0.5, 0.6, 0.7, 0.8}) {
        int tp = 0, fp = 0, tn = 0, fn = 0;
        for (auto& p : pairs) {
            bool pred = similarity(to_phonetic(p.a), to_phonetic(p.b)) >= t;
            if ( pred &&  p.expected) ++tp;
            if ( pred && !p.expected) ++fp;
            if (!pred && !p.expected) ++tn;
            if (!pred &&  p.expected) ++fn;
        }
        double prec = (tp + fp) ? 100.0 * tp / (tp + fp) : 0.0;
        double rec  = (tp + fn) ? 100.0 * tp / (tp + fn) : 0.0;
        double acc  = 100.0 * (tp + tn) / total;

        if (acc > best_acc) { best_acc = acc; best_t = t; }

        cout << fixed << setprecision(2)
             << "  " << setw(4) << t
             << "  " << setw(4) << tp << " " << setw(4) << fp
             << " "  << setw(4) << tn << " " << setw(4) << fn
             << "   " << setw(6) << prec << "%  "
             << setw(6) << rec << "%   "
             << setw(6) << acc  << "%\n";
    }
    cout << "--------------------------------------------------------------\n"
         << "Лучший порог: T=" << best_t
         << "   точность = " << best_acc << "%\n\n";

    // ---------- false negatives ----------
    cout << "==============================================================\n"
         << "  ПРОПУЩЕННЫЕ РИФМЫ (MISS) при T=" << best_t << ":\n";
    int n_miss = 0;
    for (auto& p : pairs) {
        if (!p.expected) continue;
        double s = similarity(to_phonetic(p.a), to_phonetic(p.b));
        if (s < best_t) {
            ++n_miss;
            cout << "  MISS  " << p.a << " / " << p.b
                 << "   sim=" << s
                 << "   phon: " << to_phonetic(p.a)
                 << " / "   << to_phonetic(p.b)
                 << "   — "  << p.note << "\n";
        }
    }
    if (!n_miss) cout << "  (нет — все рифмы найдены)\n";
    cout << "\n";

    // ---------- false positives ----------
    cout << "==============================================================\n"
         << "  ЛОЖНЫЕ РИФМЫ (FALS) при T=" << best_t << ":\n";
    int n_fals = 0;
    for (auto& p : pairs) {
        if (p.expected) continue;
        double s = similarity(to_phonetic(p.a), to_phonetic(p.b));
        if (s >= best_t) {
            ++n_fals;
            cout << "  FALS  " << p.a << " / " << p.b
                 << "   sim=" << s
                 << "   phon: " << to_phonetic(p.a)
                 << " / "   << to_phonetic(p.b)
                 << "   — "  << p.note << "\n";
        }
    }
    if (!n_fals) cout << "  (нет — ложных срабатываний не обнаружено)\n";
    cout << "\n";

    // ---------- полная таблица ----------
    cout << "==============================================================\n"
         << "  ПОЛНАЯ ТАБЛИЦА ПАР (сорт. по sim)\n"
         << "==============================================================\n";
    vector<pair<double, const RhymePair*>> rows;
    rows.reserve(pairs.size());
    for (auto& p : pairs)
        rows.push_back({similarity(to_phonetic(p.a), to_phonetic(p.b)), &p});
    sort(rows.begin(), rows.end(),
         [](auto& x, auto& y) { return x.first < y.first; });

    for (auto& [s, p] : rows) {
        const char* tag;
        if ( p->expected && s >= best_t) tag = "OK  ";
        else if ( p->expected)           tag = "MISS";
        else if (s >= best_t)            tag = "FALS";
        else                             tag = "ok  ";

        cout << "  " << tag << "  sim=" << fixed << setprecision(2) << setw(4) << s
             << "   " << p->a << " / " << p->b
             << "   [" << p->note << "]\n";
    }
    cout << "\n";

    cout << "==============================================================\n"
         << "  ИТОГ: точность " << best_acc << "% при T=" << best_t << "\n"
         << "==============================================================\n\n";

    // мягкий порог — если алгоритм деградирует, тест упадёт
    EXPECT_GE(best_acc, 80.0)
        << "Точность упала ниже 80%. Смотри MISS/FALS выше для анализа.";
}